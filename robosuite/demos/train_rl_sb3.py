"""
robosuite + Stable-Baselines3 (SB3) 强化学习训练脚本（优化版）

任务：Lift（让 Panda 机器人抓起桌面上的立方体）
算法：SAC（Soft Actor-Critic）
硬件适配：4060 Ti 16GB（低维状态输入，GPU 利用率低，瓶颈在 CPU 仿真）

核心优化点（相比最简版本的改进）：
    1. 向量化环境（SubprocVecEnv）：8 个环境多进程并行采集数据，吞吐量提升数倍
    2. 观测与奖励归一化（VecNormalize）：稳定训练、加速收敛
    3. 训练步数提升到 50 万：Lift 任务通常需要 30-50 万步才能稳定成功
    4. 强制使用 GPU：低维状态下 GPU 利用率不高，但仍比 CPU 快

运行方式：
    python robosuite/demos/train_rl_sb3.py
"""

import numpy as np
import robosuite as suite
from robosuite.wrappers import GymWrapper
from stable_baselines3 import SAC
from stable_baselines3.common.vec_env import SubprocVecEnv, VecNormalize
from stable_baselines3.common.monitor import Monitor


# =============================================================================
# 第一步：定义环境工厂函数
# =============================================================================
# 为什么需要"工厂函数"而不是直接创建环境？
#   因为向量化环境需要多个独立的环境实例，每个实例必须独立创建。
#   SubprocVecEnv 接收一个函数列表，每个函数返回一个环境实例。
# =============================================================================

def make_env():
    """
    创建一个 robosuite 环境，并用 GymWrapper 包装为 Gym API。

    返回:
        GymWrapper: 符合 Gym API 的环境实例
    """

    # =========================================================================
    # robosuite 原生环境配置
    # =========================================================================
    # 这些参数决定了 RL 的"游戏规则"，对训练效果影响极大
    # =========================================================================
    env = suite.make(
        # ---- 任务与机器人 ----
        "Lift",                        # 任务名：让机器人抓起桌面上的立方体
        robots="Panda",                # 机器人型号：Franka Panda 7 自由度机械臂

        # ---- 渲染设置（训练时全部关闭以提速）----
        has_renderer=False,            # 关闭可视化窗口（训练时关，调试时开）
        has_offscreen_renderer=False,  # 关闭离屏渲染（不用图像观测时必须关）
        use_camera_obs=False,          # 关闭图像观测（新手必关！图像 RL 慢 10-100 倍）

        # ---- RL 时间设置 ----
        control_freq=20,               # 控制频率 20Hz（每秒 20 个动作，每步 50ms）
                                       #   太高：动作精细但样本爆炸
                                       #   太低：动作粗糙，难以完成精细操作
        horizon=200,                   # 每 episode 最大 200 步（200×50ms=10 秒模拟时间）
                                       #   太短：任务没完成就被截断
                                       #   太长：浪费时间在无意义的探索上

        # ---- 奖励设置 ----
        reward_shaping=True,           # 开启稠密奖励（新手必开！）
                                       #   True:  距离越近奖励越高 + 抓住奖励 + 抬起奖励
                                       #   False: 只有抬起成功才给奖励（几乎学不会）
    )

    # =========================================================================
    # GymWrapper：把 robosuite 的 OrderedDict 观测转成 numpy 数组
    # =========================================================================
    # robosuite 原生返回：
    #   obs = {"robot0_joint_pos": [...], "object-state": [...], ...}
    #   step() 返回 (obs, reward, done, info)  # 4 元组
    #
    # Gym API 要求：
    #   obs = np.array([...])                   # 一维数组
    #   step() 返回 (obs, reward, terminated, truncated, info)  # 5 元组
    #
    # GymWrapper 自动完成这个转换，并生成 observation_space 和 action_space
    # =========================================================================
    env = GymWrapper(env)

    # =========================================================================
    # Monitor：记录每个 episode 的奖励和长度（关键！）
    # =========================================================================
    # 没有 Monitor，SB3 无法追踪 episode 结束，TensorBoard 中就不会出现：
    #   rollout/ep_rew_mean  （平均回合奖励 —— 最核心的训练指标）
    #   rollout/ep_len_mean  （平均回合长度）
    #
    # Monitor 会在 info 中注入 "episode" 键，SB3 据此计算滑动平均值并记录到 TensorBoard
    # =========================================================================
    return Monitor(env)


# =============================================================================
# 第二步：创建向量化环境（核心优化 1）
# =============================================================================
# 为什么需要向量化？
#   单个环境每步只能采集 1 个样本，而神经网络更新需要大量样本。
#   多个环境并行采集，数据吞吐量直接翻倍。
#
# DummyVecEnv vs SubprocVecEnv：
#   - DummyVecEnv:   单进程内循环跑多环境，没真正利用多核，fps 偏低
#   - SubprocVecEnv: 每个环境一个独立进程，真正多核并行，fps 提升 2-4 倍
#
# 为什么选 8 个？
#   - 4060 Ti 的 CPU 通常搭配 8 核左右的处理器
#   - 8 个环境能充分利用 CPU 多核，同时不会让系统卡顿
#   - 如果 CPU 核心少（4 核），可以降到 4 个
#
# 重要：SubprocVecEnv 必须放在 if __name__ == '__main__': 保护块中
#   子进程会重新 import 主模块，若不保护会导致无限递归创建子进程
# =============================================================================
NUM_ENVS = 8  # 并行环境数量，可根据 CPU 核心数调整

# =============================================================================
# 继续训练配置
# =============================================================================
# RESUME=True：加载已有模型和归一化参数，在已有基础上继续训练
# RESUME=False：从头开始训练
#
# 继续训练的原理：
#   - SAC.load() 加载模型权重（actor/critic 网络参数 + 优化器状态）
#   - VecNormalize.load() 加载归一化的 running mean/std
#   - model.learn(total_timesteps=N) 中的 N 是"总目标步数"
#     例如之前训练了 50 万步，设 N=1000000 会继续训练到 100 万步（再跑 50 万步）
#
# 什么时候需要继续训练？
#   - 训练完 50 万步效果还不够好（奖励还在上升但没收敛）
#   - 想在不改变超参数的前提下多训一些步数
# =============================================================================
RESUME = True                  # 改为 True 即可继续训练
MODEL_PATH = "lift_panda_sac_optimized.zip"
VEC_NORMALIZE_PATH = "vec_normalize.pkl"
TOTAL_TIMESTEPS = 1000000      # 总目标步数（继续训练时设为更大的值）


# =============================================================================
# 主函数：包含环境创建、训练、保存、测试的完整流程
# =============================================================================
def main():
    """
    RL 训练主流程：创建环境 → 训练 → 保存 → 测试
    """

    print(f"正在创建 {NUM_ENVS} 个并行环境（SubprocVecEnv 多进程）...")
    env = SubprocVecEnv([make_env for _ in range(NUM_ENVS)])

    # =========================================================================
    # 第三步：观测与奖励归一化（核心优化 2）
    # =========================================================================
    # 为什么需要归一化？
    #   不同观测分量量级差异极大：
    #     - 关节角度：约 [-3.14, 3.14] 弧度
    #     - 关节速度：约 [-10, 10] rad/s
    #     - 物体位姿：约 [-1, 1] 米
    #     - 像素值（如果用图像）：[0, 255]
    #
    #   神经网络不喜欢量级差异大的输入，会导致：
    #     - 梯度不稳定，某些特征主导学习
    #     - 学习率难以调整
    #     - 训练收敛慢
    #
    # VecNormalize 做的事：
    #   - 观测归一化：用 running mean/std 实时归一化到均值 0、方差 1
    #   - 奖励归一化：用 running std 归一化奖励（不改变信号方向，只改变量级）
    #
    # 注意：
    #   - 归一化参数是训练时动态学习的，必须保存
    #   - 测试时必须加载相同的归一化参数，否则策略会"看不懂"观测
    # =========================================================================
    # =========================================================================
    # 加载已有归一化参数（继续训练时）
    # =========================================================================
    if RESUME:
        print(f"加载已有归一化参数：{VEC_NORMALIZE_PATH}")
        env = VecNormalize.load(VEC_NORMALIZE_PATH, env)
    else:
        env = VecNormalize(env, norm_obs=True, norm_reward=True)

    # =========================================================================
    # 第四步：创建 SAC 算法实例
    # =========================================================================
    # SAC（Soft Actor-Critic）特点：
    #   - 离线策略（off-policy）：能复用旧经验，样本效率高
    #   - 最大熵强化学习：鼓励探索，避免过早收敛到次优解
    #   - Actor-Critic 结构：同时学策略网络和价值网络
    #   - 当前连续控制 RL 的首选算法之一
    # =========================================================================
    # =========================================================================
    # 创建或加载 SAC 模型
    # =========================================================================
    # 继续训练时用 SAC.load() 加载已有模型，包括网络权重和优化器状态
    # 从头训练时用 SAC() 创建新模型
    # =========================================================================
    sac_kwargs = dict(
        # ---- 训练日志 ----
        verbose=1,                     # 打印训练进度（0=静默，1=基本信息，2=详细）
        tensorboard_log="./logs/sac_lift/",  # TensorBoard 日志目录，用于可视化训练曲线

        # ---- 核心超参数 ----
        learning_rate=3e-4,            # 学习率：神经网络参数更新的步长
                                       #   太大（1e-3）：训练震荡，可能学崩
                                       #   太小（1e-5）：收敛极慢
                                       #   3e-4 是 SAC 的黄金值，一般不用改

        buffer_size=200000,            # 经验回放池大小：存储历史 (s, a, r, s') 的池子
                                       #   8 个并行环境数据量大，池子也加大
                                       #   太小：忘记旧经验，训练不稳定
                                       #   太大：内存占用高（200k × 32维 ≈ 25MB，不慌）

        batch_size=256,                # 每次网络更新从池子中采样的样本数
                                       #   越大越稳定但越慢
                                       #   256 是 SAC 标配，一般不用改

        # ---- 软更新参数 ----
        tau=0.005,                     # 目标网络软更新系数
                                       #   目标网络 = tau × 当前网络 + (1-tau) × 目标网络
                                       #   越大：目标网络更新越快，但训练可能不稳定
                                       #   越小：更新越慢，但更稳定
                                       #   0.005 是 SAC 默认值

        gamma=0.99,                    # 折扣因子：未来奖励的重要性
                                       #   0.99：重视长期回报（适合大多数任务）
                                       #   0.9：只关心近期回报（适合短时任务）
                                       #   Lift 任务需要多步规划，用 0.99

        # ---- 网络结构 ----
        policy_kwargs=dict(
            net_arch=[256, 256],       # 策略网络结构：两个隐藏层，每层 256 个神经元
                                       #   Lift 是简单任务，[256, 256] 足够
                                       #   更复杂任务可以试 [400, 300]
                                       #   想加速可以试 [128, 128]
            use_sde=False,             # 是否使用随机策略梯度估计（State Dependent Exploration）
                                       #   必须与已保存模型一致，否则 SAC.load() 会报 policy_kwargs 不匹配
        ),

        # ---- 设备 ----
        device="cuda",                 # 强制使用 GPU
                                       #   低维状态下 GPU 利用率不高，但仍比 CPU 快
                                       #   4060 Ti 16GB 显存绰绰有余
                                       #   若无 GPU 可改为 "cpu"
    )

    if RESUME:
        print(f"加载已有模型：{MODEL_PATH}")
        model = SAC.load(MODEL_PATH, env=env, **sac_kwargs)
    else:
        model = SAC("MlpPolicy", env, **sac_kwargs)

    # =========================================================================
    # 第五步：训练（核心优化 3：步数提升到 50 万）
    # =========================================================================
    # 为什么 50 万步？
    #   - Lift 是简单任务，但 10 万步通常只能看到"开始接近物体"
    #   - 30-50 万步才能稳定抓起并抬起
    #   - 复杂任务（如 Stack、Assembly）可能需要 100-300 万步
    #
    # 时间估算（4060 Ti + 8 并行环境）：
    #   - 50 万步约需 20-40 分钟
    #   - 若 CPU 较弱可能需要 1 小时
    #
    # 如何判断训练是否成功？
    #   观察 SB3 打印的 ep_rew_mean（平均回合奖励）：
    #     - 0 - 0.5：还没学会抓取
    #     - 0.5 - 1.5：会接近物体，偶尔抓到
    #     - 1.5 - 2.0：基本学会抓取
    #     - 2.0+：稳定抬起，任务成功
    # =========================================================================
    print(f"\n开始训练，总目标步数：{TOTAL_TIMESTEPS}")
    if RESUME:
        print("（继续训练模式：在已有模型基础上追加训练）")
    print(f"预计时间：20-40 分钟（取决于 CPU 性能）")
    print("=" * 60)

    model.learn(total_timesteps=TOTAL_TIMESTEPS)

    # =========================================================================
    # 第六步：保存模型与归一化参数
    # =========================================================================
    # 必须同时保存两个文件：
    #   1. 模型权重（.zip）：策略网络的参数
    #   2. 归一化参数（.pkl）：VecNormalize 的 running mean/std
    #
    # 测试时缺一不可：
    #   - 只加载模型：策略会"看不懂"未归一化的观测
    #   - 只加载归一化：没有策略网络无法决策
    # =========================================================================
    model.save("lift_panda_sac_optimized")
    env.save("vec_normalize.pkl")
    print("\n训练完成！已保存：")
    print("  - 模型：lift_panda_sac_optimized.zip")
    print("  - 归一化参数：vec_normalize.pkl")

    # =========================================================================
    # 第七步：快速测试训练好的策略
    # =========================================================================
    # 注意：测试时也要用 VecNormalize 包装，但只归一化观测不归一化奖励
    # （测试时不需要奖励信号，只要观测归一化对齐训练时即可）
    # =========================================================================
    print("\n" + "=" * 60)
    print("开始测试训练好的策略...")

    # 测试时关闭训练模式，只做推理
    env.training = False
    # 测试时关闭奖励归一化（推理时不需要奖励，但观测必须归一化）
    env.norm_reward = False

    episode_rewards = []
    for i in range(10):  # 测试 10 个 episode
        obs = env.reset()
        episode_reward = 0
        done = [False]

        while not done[0]:
            # deterministic=True：用策略均值而非采样，表现更稳定
            action, _ = model.predict(obs, deterministic=True)
            obs, reward, done, info = env.step(action)
            episode_reward += reward[0]

        episode_rewards.append(episode_reward)
        print(f"Episode {i+1}: 奖励 = {episode_reward:.2f}")

    print(f"\n平均奖励：{np.mean(episode_rewards):.2f}")
    print(f"最高奖励：{np.max(episode_rewards):.2f}")
    print(f"最低奖励：{np.min(episode_rewards):.2f}")


# =============================================================================
# 入口点：SubprocVecEnv 要求主模块可被安全 import
# =============================================================================
# if __name__ == '__main__' 保护块的作用：
#   SubprocVecEnv 的子进程会重新 import 主模块来加载 make_env 函数。
#   若没有这个保护，子进程 import 时会再次执行 SubprocVecEnv 创建逻辑，
#   导致子进程再创建子进程，无限递归。
#   这个保护确保只有直接运行脚本时才执行 main()，被 import 时不执行。
# =============================================================================
if __name__ == "__main__":
    main()


